import Foundation

/// Результат отправки сообщения: ответ ассистента **и** переписка, в которой он оказался.
///
/// Новый разговор заводит сервер, а не клиент: до первого ответа идентификатора
/// не существует. Если не вернуть его сюда, второе сообщение уйдёт снова с `chatID: nil`
/// и создаст ещё одну переписку, а сам чат никогда не появится в списке —
/// переименовывать и удалять будет нечего.
struct SentMessage: Equatable, Sendable {
    let chatID: ChatSummary.ID
    /// Название, которым сервер назвал переписку. `nil` — названия он не прислал,
    /// и заголовок остаётся тем, что уже стоит на экране.
    let chatTitle: String?
    let message: ChatMessage
}
