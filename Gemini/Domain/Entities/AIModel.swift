import Foundation

/// Модель генерации.
///
/// Сущность домена: она ничего не знает о том, откуда взялся каталог.
/// Сейчас его отдаёт заглушка, позже — ручка каталога моделей.
/// `nonisolated`, потому что сущность читают и сетевые репозитории — акторы
/// вне главного. Данные тут неизменяемые, изолировать нечего, а без пометки
/// сравнение `capability` из репозитория в Swift 6 станет ошибкой.
nonisolated struct AIModel: Identifiable, Equatable {
    enum Capability: Equatable {
        case text
        case image
        case video
    }

    let id: String
    let title: String
    let subtitle: String
    let capability: Capability
    /// Модель, которую backend считает основной. Выбор по ней, а не по первой
    /// в списке: порядок каталога сервер не обещает.
    var isDefault = false
    /// Сколько кредитов стоит одна генерация — самая дешёвая её ступень.
    /// Цену называет каталог генерации и только он: у чат-моделей её нет.
    var credits: Int?
    /// Ступени качества, которые модель принимает, её же словами: у изображений
    /// это «1K»/«2K»/«4K», у Veo — «720p»/«1080p»/«4k», а Kling не принимает
    /// ступеней вовсе. Пустой список — параметр не отправлять.
    var resolutions: [String] = []
}
