/// Ошибки переписки, понятные экранам.
///
/// У трёх случаев есть `chatID`: сервер создаёт разговор до того, как решит,
/// блокировать ответ или нет, — отбрасывать этот id на ошибке нельзя, иначе
/// следующая отправка уйдёт без него и заведёт **ещё один** разговор вместо
/// повтора в том же. `nil` — законное значение только для самого первого
/// сообщения нового чата, если сервер обрубился до того, как успел его отдать.
enum ChatError: Error, Equatable {
    case emptyMessage
    /// Генерация не удалась — экран показывает красный пузырь и кнопку повтора.
    case generationFailed(chatID: ChatSummary.ID?)
    /// Кончились токены.
    case outOfTokens(chatID: ChatSummary.ID?)
    /// Исчерпан дневной лимит сообщений.
    case dailyLimitReached(chatID: ChatSummary.ID?)
}
