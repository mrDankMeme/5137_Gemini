import Foundation

/// Генерация изображений и видео.
///
/// Отдельно от переписки, потому что и на сервере это отдельный раздел: чат
/// медиа-задач не заводит — он лишь опишет картинку словами. Модель, цена в
/// кредитах и ступени качества живут в своём каталоге, а результат — в задаче,
/// которую надо опрашивать до готовности.
protocol MediaGenerationRepositoryProtocol: Sendable {
    /// Запускает генерацию, ждёт результат и возвращает его вместе с
    /// перепиской, в которой он оказался, — как и отправка сообщения.
    ///
    /// Переписку здесь заводит не сервер, а само приложение: у задачи
    /// генерации сессии чата нет и в списке сервера она не появится.
    ///
    /// `referenceImages` — исходники для «по картинке»: часть моделей умеет
    /// только редактировать, и без них задача не имеет смысла.
    func generate(
        prompt: String,
        chatID: ChatSummary.ID?,
        model: AIModel,
        kind: LibraryItem.Kind,
        settings: GenerationSettings,
        referenceImages: [ChatAttachment]
    ) async throws -> SentMessage
}
